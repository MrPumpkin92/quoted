"""docs/catalog-sources.md: the evidence behind every seal, generated from supabase/catalog/ so it
outlives build/. Run `scripts/catalog.sh sources-doc` after each batch."""

import datetime
import os
import re

from . import config, pd, registry, starters as starters_mod

STRICT_FAILS_NOTE = ("These starters fail the strict rule today. They stay live until the founder decides D4 "
                     "(plan section 3.1); that is an accepted, dated risk, not a mitigation.")


def _y(y):
    return "?" if y is None else ("%d BCE" % -y if y < 0 else str(y))


def _cell(s):
    return re.sub(r"\s+", " ", (s or "")).replace("|", "\\|").strip()


def write(path=None):
    reg = registry.Registry.load()
    quotes = sorted(registry.read_jsonl(os.path.join(config.data_dir(), "quotes.jsonl")), key=lambda q: q["id"])
    lock = {r["ref"]: r for r in registry.read_jsonl(config.lock_path())}
    fixtures = {f["id"]: f for f in registry.read_jsonl(os.path.join(config.data_dir(), "fixtures", "starters.jsonl"))}
    rejects = registry.read_jsonl(os.path.join(config.data_dir(), "fixtures", "rejects.jsonl"))
    today = datetime.date.today()
    c = pd.cutoffs(today)
    out = [
        "# Catalog sources",
        "",
        "Generated by `scripts/catalog.sh sources-doc` from `supabase/catalog/`. Do not edit by hand.",
        "",
        "Every catalog quote was found in a pinned public-domain edition, and its body is the text of that",
        "edition's matched span (typography normalised, trims recorded). This file is the record a reviewer,",
        "App Review or a rights holder can check each seal against.",
        "",
        "## Authorization record",
        "",
        "- **The public-domain rule**, computed from the date (plan section 3.1). As of %s:" % today.isoformat(),
        "  - US: the text used (original, translation or edition) was first published in %d or earlier." % c["us"],
        "  - Strict, for every App Store storefront: every contributor (author, translator, reporter) died in %d or" % c["strict"],
        "    earlier, and none is recorded \"mort pour la France\". An unknown death year fails.",
        "  - Every non-starter row passes both; `supabase/tests/database/16_catalog.test.sql` re-checks it from the",
        "    database on every test run.",
        "- **Project Gutenberg** supplies most texts, fetched from its rsync mirror. Its permission page says no",
        "  permission is needed to use quotes from Project Gutenberg items (as recorded in",
        "  docs/catalog-population-plan.md section 2, read 2026-10-28). Credit: Project Gutenberg volunteers. The",
        "  name is not used in App Store text or marketing.",
        "- **Wikisource** supplies the scan-backed texts. Each seal pins the page revision and the Page: revisions",
        "  it transcludes (`supabase/catalog/corpus.lock.jsonl`). Wikisource's own translations are never used.",
        "- **Wikiquote** (CC BY-SA 4.0) is used only to build the internal reject list of misattributed and",
        "  disputed lines. No Wikiquote text is stored in the repository or shown in the app. Credit: English",
        "  Wikiquote contributors.",
        "- **Exceptions (D4).** %s" % STRICT_FAILS_NOTE,
        "",
    ]
    exc = []
    for sid, fx in sorted(fixtures.items()):
        for j in fx.get("judgements", []):
            if j["kind"] == "pd_exception":
                exc.append("  - #%d: %s" % (sid, j["note"]))
    out += exc + [""]

    out += ["## Catalog quotes", "",
            "| id | Quote | Author | Work and location | Checked against | Public domain | Context |",
            "|---:|---|---|---|---|---|---|"]
    for q in quotes:
        w = reg.works[q["work_id"]]
        a = reg.authors[q["author_id"]]
        wa = reg.authors[w["author_id"]]
        ch = q["checked"]
        deaths = ["%s d. %s" % (a["name"], _y(a.get("died_year")))]
        if wa["id"] != a["id"]:
            deaths.append("%s d. %s" % (wa["name"], _y(wa.get("died_year"))))
        if w.get("translator"):
            deaths.append("trans. %s d. %s" % (w["translator"], _y(w.get("translator_died_year"))))
        if w.get("reporter"):
            deaths.append("reported by %s d. %s" % (w["reporter"], _y(w.get("reporter_died_year"))))
        row = lock.get(ch["ref"], {})
        pinned = "%s, %s %d–%d, body sha256 %s…%s" % (
            "<%s>" % q["source_url"], ch["match_kind"], ch["start"], ch["end"], ch["body_sha256"][:12],
            (", updated %s" % row["last_updated"]) if row.get("last_updated") else (
                ", oldid %s" % row["oldid"] if row.get("oldid") else ""))
        edits = [e["kind"] for e in (q.get("edits") or [])]
        ctx = "…%s **[quote]** %s…" % (_cell(q.get("context_before", ""))[-90:], _cell(q.get("context_after", ""))[:90])
        out.append("| %d | %s | %s | *%s*, %s%s%s | %s | edition %s; %s | %s |" % (
            q["id"], _cell(q["body"].replace("\n", " / "))[:140], a["name"], _cell(w["citation"]), _cell(q["source_location"]),
            ("; spoken by " + q["speaker"]) if q.get("speaker") else "",
            ("; edits: " + ", ".join(edits)) if edits else "", pinned, _y(w["edition_year"]), "; ".join(deaths), ctx))
    if not quotes:
        out.append("| | No catalog quotes beyond the starters yet. | | | | | |")
    out += ["", "## The 60 starters", "",
            "Their locations and sources are in docs/starter-pack-sources.md. The verifier's gate re-renders all 60",
            "byte for byte from their pinned sources. It found these edits, which the starter doc does not always note:",
            ""]
    shipped = {q["id"]: q for q in starters_mod.load()}
    for sid, fx in sorted(fixtures.items()):
        ed = fx["expect"]["edits"]
        if ed:
            out.append("- #%d %s: %s" % (sid, shipped[sid]["author"], ", ".join(e["kind"] + ("(" + e["was"] + ")" if e.get("was") else "") for e in ed)))
    out += ["", "## Known misattributions (never sealed)", "",
            "The gate checks that none of these passes under its false attribution.", "",
            "| Line | Usually credited to | Expected |", "|---|---|---|"]
    for r in rejects:
        out.append("| %s | %s | %s |" % (_cell(r["text"]), r["author"], ", ".join(r["expect_any_of"])))
    path = path or os.path.join(config.REPO, "docs", "catalog-sources.md")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    print("wrote", os.path.relpath(path, config.REPO))
    return 0
